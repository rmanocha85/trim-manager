const {chromium}=require('playwright');
const http=require('node:http'),fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
(async()=>{
  const server=http.createServer((req,res)=>{
    const file=req.url.split('?')[0]==='/roster-core.js'?'roster-core.js':'index.html';
    res.setHeader('Content-Type',file.endsWith('.js')?'text/javascript':'text/html');res.end(fs.readFileSync(path.join(root,file)));
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  let browser;
  try{
    browser=await chromium.launch({headless:true,channel:process.env.TRIM_BROWSER_CHANNEL||'chrome'});
    const context=await browser.newContext({viewport:{width:1500,height:950}}),page=await context.newPage();
    const errors=[],requests=[];let discard=false,prompts=0;
    page.on('pageerror',e=>errors.push(e.message));
    page.on('dialog',async d=>{if(d.type()==='confirm'){prompts++;await(discard?d.accept():d.dismiss());}else await d.accept();});
    const disk={patients:[{id:'synthetic',name:'Synthetic Patient',phn:'9000000001',ava:'900001',unit:'cedar',room:'1',codes:'TEST'}],units:[{id:'cedar',name:'CEDAR',floor:1}],billingDates:[],otherPatients:[{id:'other-synthetic',name:'Synthetic Coverage'}]};
    let responseStatus=200,gate=null,revision=1;
    await page.route('https://www.googleapis.com/**',async route=>{
      const req=route.request();requests.push(req.method());assert.ok(req.url().includes('1AaGORl08dctBiZiLAEshmnIMJ6U_GBX3'));
      if(gate)await gate;
      await route.fulfill({status:responseStatus,json:responseStatus===200?(req.url().includes('alt=media')?disk:{etag:'r'+revision}):{error:'synthetic unauthorized'}});
    });
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    const control=page.locator('#btn-connect');
    assert.equal(await page.locator('#btn-sync').count(),0);
    assert.equal(await control.textContent(),'● Connect to Drive');
    await page.evaluate(()=>{window.google={accounts:{oauth2:{initTokenClient:options=>({requestAccessToken:()=>options.callback({access_token:'synthetic',expires_in:3600})})}}};});
    await control.click();await page.waitForFunction(()=>document.getElementById('btn-connect').dataset.state==='ok');
    assert.equal(await control.textContent(),'● Drive connected');assert.equal(await page.evaluate(()=>state.patients.length),1);
    disk.patients[0].room='REMOTE';revision++;
    let release;gate=new Promise(resolve=>release=resolve);
    await control.click();await page.waitForFunction(()=>connectionChecking);
    assert.equal(await control.textContent(),'◌ Checking Drive…');
    release();gate=null;await page.waitForFunction(()=>!connectionChecking);
    assert.equal(await page.evaluate(()=>state.patients[0].room),'REMOTE');
    assert.equal(await page.evaluate(()=>currentRoster().otherPatients.length),1);assert.equal(prompts,0);
    await page.evaluate(()=>{state.patients[0].room='UNSAVED';writeBlocked=true;setSS('NOT SAVED — pending roster edit',false);});
    await control.click();await page.waitForFunction(()=>!connectionChecking);
    assert.equal(prompts,1);assert.equal(await page.evaluate(()=>state.patients[0].room),'UNSAVED');
    assert.equal(await page.locator('#ss').textContent(),'NOT SAVED — pending roster edit');
    discard=true;await control.click();await page.waitForFunction(()=>!connectionChecking);
    assert.equal(prompts,2);assert.equal(await page.evaluate(()=>state.patients[0].room),'REMOTE');
    assert.equal(await page.evaluate(()=>writeBlocked),false);
    // Background checks may flag remote changes, but only a button click replaces the list.
    disk.patients[0].room='NEWER';revision++;
    await page.evaluate(()=>checkDriveConnection());
    assert.equal(await page.evaluate(()=>state.patients[0].room),'REMOTE');assert.equal(await page.evaluate(()=>writeBlocked),true);
    await control.click();await page.waitForFunction(()=>!connectionChecking);
    assert.equal(await page.evaluate(()=>state.patients[0].room),'NEWER');assert.equal(prompts,2);
    discard=false;await page.locator('#in-name').fill('Unfinished synthetic patient');
    await control.click();await page.waitForFunction(()=>!connectionChecking);
    assert.equal(prompts,3);assert.equal(await page.locator('#in-name').inputValue(),'Unfinished synthetic patient');
    await page.locator('#in-name').fill('');
    await context.setOffline(true);await page.waitForFunction(()=>document.getElementById('btn-connect').dataset.state==='error');
    assert.equal(await control.textContent(),'● Reconnect Drive');
    await context.setOffline(false);await page.waitForFunction(()=>document.getElementById('btn-connect').dataset.state==='ok');
    responseStatus=401;await control.click();await page.waitForFunction(()=>!connectionChecking);
    assert.equal(await control.textContent(),'● Reconnect Drive');assert.equal(await page.evaluate(()=>state.googleToken),null);
    disk.patients[0].room='AFTER RECONNECT';revision++;responseStatus=200;
    await control.click();await page.waitForFunction(()=>document.getElementById('btn-connect').dataset.state==='ok');
    assert.equal(await page.evaluate(()=>state.patients[0].room),'AFTER RECONNECT');
    fs.mkdirSync(path.join(root,'work'),{recursive:true});
    await page.locator('header').screenshot({path:path.join(root,'work','single-drive-button-synthetic.png')});
    await page.evaluate(()=>acceptDriveToken({access_token:'short-synthetic',expires_in:.01}));
    await page.waitForFunction(()=>document.getElementById('btn-connect').dataset.state==='error');
    assert.equal(await page.evaluate(()=>state.googleToken),null);
    assert.ok(requests.length>0&&requests.every(method=>method==='GET'));
    assert.deepEqual(errors,[]);console.log('Single Drive button browser checks passed: initial load, refresh, conflict recovery, cancel/discard, unfinished form, background checks, offline, 401, reconnect and expiry; no writes.');
  }finally{if(browser)await browser.close();server.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
